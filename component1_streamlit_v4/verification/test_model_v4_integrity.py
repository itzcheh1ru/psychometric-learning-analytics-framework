"""
test_model_v4_integrity.py
==========================
Comprehensive Automated Verification & Reliability Suite for Component 1 (Version 4).

Validation Checkpoints:
1. Model loading from disk without retraining.
2. Feature schema conformance (68 features).
3. Prediction validity on typical student profile.
4. Calibrated probability validity (range [0, 1], sums to 1.0).
5. Monotonic ordinal response test (low vs high delegation).
6. Robustness against missing, dirty, and out-of-range inputs.
7. TreeSHAP explanation compatibility and directionality.
8. Continuous regression prediction validity.
9. Privacy protection (zero PII exposure) and mandatory research disclaimer.

Outputs:
  - Model Training/v4_performance_experiments/verification/v4_verification_report.json
"""

import json
import os
import sys
import unittest
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import shap

SCRIPT_DIR = Path(__file__).resolve().parent
EXPERIMENT_DIR = SCRIPT_DIR.parent
SCRIPTS_DIR = EXPERIMENT_DIR / "scripts"
MODELS_DIR = EXPERIMENT_DIR / "models"
REPORTS_DIR = EXPERIMENT_DIR / "reports"
VERIF_DIR = EXPERIMENT_DIR / "verification"

sys.path.append(str(SCRIPTS_DIR))
from train_model_v4 import CalibratedHybridEnsemble, CalibratedThresholdedRidge

DISCLAIMER = (
    "RESEARCH DISCLAIMER: This risk prediction is generated by an academic machine learning "
    "model (Component 1, J26-DS-310) for exploratory educational purposes only. It does not "
    "constitute a psychological assessment, cognitive diagnosis, or academic penalty."
)


class TestComponent1Version4Integrity(unittest.TestCase):
    """Rigorous verification test suite for Version 4 model artifacts."""

    @classmethod
    def setUpClass(cls):
        # Load metadata
        with open(MODELS_DIR / "pipeline_metadata_v4.json") as f:
            cls.metadata = json.load(f)
        cls.feature_names = cls.metadata["feature_names"]

        # Load models
        raw_champ = joblib.load(MODELS_DIR / "calibrated_champion_v4.joblib")
        if isinstance(raw_champ, dict):
            cls.champion = CalibratedThresholdedRidge(
                alpha=raw_champ.get("alpha", 30.0),
                cut1=raw_champ.get("cut1", 2.667),
                cut2=raw_champ.get("cut2", 3.500),
                residual_std=raw_champ.get("residual_std", 0.585)
            )
            cls.champion.reg_ = raw_champ.get("estimator")
            cls.champion.classes_ = np.array([0, 1, 2])
        else:
            cls.champion = raw_champ

        cls.extra_trees = joblib.load(MODELS_DIR / "extra_trees_v4.joblib")
        cls.catboost = joblib.load(MODELS_DIR / "catboost_v4.joblib")
        cls.thresholded_ridge = joblib.load(MODELS_DIR / "thresholded_ridge_v4.joblib")
        cls.continuous_reg = joblib.load(MODELS_DIR / "continuous_regressor_v4.joblib")

        # Tree explainer on base ExtraTrees
        cls.explainer = shap.TreeExplainer(cls.extra_trees.estimator)

    def test_01_model_loading_without_retraining(self):
        """Verify all 5 model artifacts load successfully from disk without retraining."""
        self.assertIsNotNone(self.champion)
        self.assertIsNotNone(self.extra_trees)
        self.assertIsNotNone(self.catboost)
        self.assertIsNotNone(self.thresholded_ridge)
        self.assertIsNotNone(self.continuous_reg)
        print("  ✓ Checkpoint 1: All 5 model artifacts loaded successfully from disk.")

    def test_02_feature_schema_conformance(self):
        """Verify feature schema matches exactly 68 features without target leakage."""
        self.assertEqual(len(self.feature_names), 68)
        forbidden = [
            "co_score", "co_risk", "Q10_rely_memory", "Q11_avoid_mental_effort",
            "Q12_accept_without_understanding", "Q13_less_problem_solving",
            "Q14_depend_on_ai", "Q15_reduces_thinking", "Q37_important_part",
            "email", "name", "id", "timestamp"
        ]
        for f in forbidden:
            self.assertNotIn(f.lower(), [col.lower() for col in self.feature_names])
        print("  ✓ Checkpoint 2: Feature schema strictly conforms (68 features, zero leakage).")

    def test_03_prediction_validity(self):
        """Verify prediction for a typical student profile."""
        sample_input = pd.DataFrame(np.zeros((1, 68)), columns=self.feature_names)
        sample_input["ai_usage_freq"] = 3
        sample_input["Q20_task_delegation_freq"] = 3
        sample_input["composite_trust"] = 3.5
        sample_input["composite_autonomy"] = 3.0
        sample_input["idx_delegation_intensity"] = 9.0

        pred = self.champion.predict(sample_input)[0]
        self.assertIn(pred, [0, 1, 2])
        label = self.metadata["target_mapping"]
        inv_map = {v: k for k, v in label.items()}
        print(f"  ✓ Checkpoint 3: Prediction successful. Output class: {inv_map[pred]}")

    def test_04_calibrated_probabilities(self):
        """Verify predicted probabilities are bounded in [0, 1] and sum strictly to 1.0."""
        sample_input = pd.DataFrame(np.ones((5, 68)) * 3.0, columns=self.feature_names)
        probs = self.champion.predict_proba(sample_input)

        self.assertEqual(probs.shape, (5, 3))
        self.assertTrue(np.all(probs >= 0.0) and np.all(probs <= 1.0))
        np.testing.assert_allclose(probs.sum(axis=1), np.ones(5), rtol=1e-5)
        print("  ✓ Checkpoint 4: Probability distribution strictly valid (sums to 1.0, range [0, 1]).")

    def test_05_monotonic_ordinal_behavior(self):
        """Verify that high delegation/trust yields strictly higher risk probability than low delegation."""
        # Low risk profile
        low_profile = pd.DataFrame(np.ones((1, 68)) * 2.0, columns=self.feature_names)
        low_profile["ai_usage_freq"] = 1
        low_profile["Q20_task_delegation_freq"] = 1
        low_profile["idx_delegation_intensity"] = 1.0
        low_profile["composite_autonomy"] = 4.5
        low_profile["composite_trust"] = 2.0

        # High risk profile
        high_profile = pd.DataFrame(np.ones((1, 68)) * 4.0, columns=self.feature_names)
        high_profile["ai_usage_freq"] = 4
        high_profile["Q20_task_delegation_freq"] = 5
        high_profile["idx_delegation_intensity"] = 20.0
        high_profile["composite_autonomy"] = 1.5
        high_profile["composite_trust"] = 4.8

        p_low = self.champion.predict_proba(low_profile)[0]
        p_high = self.champion.predict_proba(high_profile)[0]

        # P(High Risk) for high profile must exceed P(High Risk) for low profile
        self.assertGreater(p_high[2], p_low[2])
        # P(Low Risk) for low profile must exceed P(Low Risk) for high profile
        self.assertGreater(p_low[0], p_high[0])
        print("  ✓ Checkpoint 5: Monotonic ordinal behavior verified (High Risk profile > Low Risk profile).")

    def test_06_robustness_against_dirty_inputs(self):
        """Verify safe handling of missing and out-of-range inputs."""
        dirty_input = pd.DataFrame(np.ones((1, 68)), columns=self.feature_names)
        dirty_input["idx_delegation_intensity"] = 999.0  # extreme
        dirty_input["composite_trust"] = -50.0          # negative out of range

        # Ensure no exception raised
        pred = self.champion.predict(dirty_input)
        probs = self.champion.predict_proba(dirty_input)
        self.assertIn(pred[0], [0, 1, 2])
        self.assertEqual(probs.shape, (1, 3))
        print("  ✓ Checkpoint 6: Extreme out-of-range inputs handled safely without failure.")

    def test_07_treeshap_explainability(self):
        """Verify TreeSHAP generates valid explanations with top factor idx_delegation_intensity."""
        sample_input = pd.DataFrame(np.ones((3, 68)) * 3.0, columns=self.feature_names)
        sample_input["idx_delegation_intensity"] = [2.0, 8.0, 18.0]

        shap_vals = self.explainer.shap_values(sample_input)
        if isinstance(shap_vals, list):
            vals_high = shap_vals[2]
        else:
            vals_high = shap_vals[:, :, 2]

        self.assertEqual(vals_high.shape, (3, 68))
        delegation_idx = self.feature_names.index("idx_delegation_intensity")
        # Higher delegation intensity must yield higher SHAP contribution to high risk
        self.assertGreater(vals_high[2, delegation_idx], vals_high[0, delegation_idx])
        print("  ✓ Checkpoint 7: TreeSHAP explanations compatible with correct directional alignment.")

    def test_08_continuous_regression_validity(self):
        """Verify continuous Ridge model produces valid co_score predictions."""
        sample_input = pd.DataFrame(np.ones((5, 68)) * 3.0, columns=self.feature_names)
        pred_cont = self.continuous_reg.predict(sample_input)
        self.assertEqual(len(pred_cont), 5)
        self.assertTrue(np.all(pred_cont >= 1.0) and np.all(pred_cont <= 5.0))
        print("  ✓ Checkpoint 8: Continuous regression produces valid score predictions within [1, 5].")

    def test_09_privacy_and_disclaimer(self):
        """Verify absence of PII and presence of mandatory research disclaimer."""
        self.assertIn("RESEARCH DISCLAIMER", DISCLAIMER)
        self.assertIn("J26-DS-310", DISCLAIMER)

        # Check that no student IDs or emails appear in metadata or feature names
        meta_str = json.dumps(self.metadata).lower()
        forbidden_terms = ["student_email", "student_id", "it234", "first_name", "last_name", "full_name"]
        for term in forbidden_terms:
            self.assertNotIn(term, meta_str)
        print("  ✓ Checkpoint 9: Privacy verified (zero PII exposure) & research disclaimer present.")


def main():
    print("=" * 80)
    print("EXECUTING VERSION 4 INTEGRITY & RELIABILITY TEST SUITE")
    print("Component 1: Explainable Cognitive Offloading Risk Model — J26-DS-310")
    print("=" * 80)

    suite = unittest.TestLoader().loadTestsFromTestCase(TestComponent1Version4Integrity)
    runner = unittest.TextTestRunner(verbosity=1)
    result = runner.run(suite)

    report_path = VERIF_DIR / "v4_verification_report.json"
    report_data = {
        "tests_run": result.testsRun,
        "failures": len(result.failures),
        "errors": len(result.errors),
        "was_successful": result.wasSuccessful(),
        "checkpoints_verified": [
            "01_model_loading_without_retraining",
            "02_feature_schema_conformance",
            "03_prediction_validity",
            "04_calibrated_probabilities",
            "05_monotonic_ordinal_behavior",
            "06_robustness_against_dirty_inputs",
            "07_treeshap_explainability",
            "08_continuous_regression_validity",
            "09_privacy_and_disclaimer"
        ]
    }
    with open(report_path, "w") as f:
        json.dump(report_data, f, indent=2)

    print(f"\nSaved test report: {report_path}")
    if result.wasSuccessful():
        print("=" * 80)
        print("ALL 9 VERSION 4 VERIFICATION CHECKPOINTS PASSED.")
        print("=" * 80)
        return 0
    else:
        print("=" * 80)
        print("SOME TESTS FAILED.")
        print("=" * 80)
        return 1


if __name__ == "__main__":
    sys.exit(main())
