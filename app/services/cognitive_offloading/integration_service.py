class Component1IntegrationServiceV4:
    """Singleton service for model inference and explainability."""

    _instance = None

    def __new__(cls, *args, **kwargs):
        if cls._instance is None:
            cls._instance = super(Component1IntegrationServiceV4, cls).__new__(cls)
            cls._instance._initialize()
        return cls._instance

    def _initialize(
        self,
        model_file=CHAMPION_MODEL_FILE,
        continuous_file=CONTINUOUS_REG_FILE,
        meta_file=METADATA_FILE,
        data_file=DATASET_REF_FILE
    ):
        if not model_file.exists():
            raise FileNotFoundError(f"Champion model not found at {model_file}")
        if not meta_file.exists():
            raise FileNotFoundError(f"Metadata file not found at {meta_file}")

        loaded = joblib.load(model_file)
        if isinstance(loaded, dict):
            self.model_dict = loaded
            self.model = loaded.get("estimator")
            self.cut1 = loaded.get("cut1", 2.667)
            self.cut2 = loaded.get("cut2", 3.500)
            self.residual_std = loaded.get("residual_std", 0.585)
        else:
            self.model_dict = None
            self.model = loaded
            self.cut1 = getattr(loaded, "cut1", 2.667)
            self.cut2 = getattr(loaded, "cut2", 3.500)
            self.residual_std = getattr(loaded, "residual_std", 0.585)

        self.continuous_reg = joblib.load(continuous_file) if continuous_file.exists() else None

        with open(meta_file, "r", encoding="utf-8") as f:
            self.metadata = json.load(f)

        self.feature_names = self.metadata["feature_names"]
        self.target_mapping = self.metadata["target_mapping"]
        self.inv_target_mapping = {v: k for k, v in self.target_mapping.items()}

        # Load reference medians and background means from metadata if available (clean & secure)
        if "reference_medians" in self.metadata and "reference_means" in self.metadata:
            self.default_features = self.metadata["reference_medians"]
            self.background_means = self.metadata["reference_means"]
        elif data_file and Path(data_file).exists():
            df_ref = pd.read_csv(data_file)
            self.default_features = df_ref[self.feature_names].median().to_dict()
            self.background_means = df_ref[self.feature_names].mean().to_dict()
        else:
            self.default_features = {f: 3.0 for f in self.feature_names}
            self.background_means = {f: 3.0 for f in self.feature_names}

        # Precompute Ridge regression coefficients for exact LinearSHAP
        if hasattr(self.model, "coef_"):
            self.coefficients = self.model.coef_
            self.intercept = self.model.intercept_
        elif hasattr(self.model, "reg_") and hasattr(self.model.reg_, "coef_"):
            self.coefficients = self.model.reg_.coef_
            self.intercept = self.model.reg_.intercept_
        elif hasattr(self.continuous_reg, "coef_"):
            self.coefficients = self.continuous_reg.coef_
            self.intercept = self.continuous_reg.intercept_
        else:
            self.coefficients = None
            self.intercept = 0.0

        logger.info(f"Loaded Version 4 Model: {self.metadata.get('champion_model', 'Thresholded Ridge')} with {len(self.feature_names)} features.")

    def _clean_and_clamp(self, key: str, val: Any, warnings_list: List[str]) -> Tuple[float, bool]:
        """Coerce, validate, and defensively clamp inputs.
        
        Returns:
            Tuple of (cleaned_float_value, is_valid_user_response)
        """
        default_val = float(self.default_features.get(key, 3.0))

        if val is None or pd.isna(val):
            warnings_list.append(f"Missing or NaN value for '{key}'; imputed using peer cohort median ({default_val:.2f}).")
            return default_val, False

        # Handle text inputs
        if isinstance(val, str):
            val_clean = val.strip().lower()
            if not val_clean:
                warnings_list.append(f"Empty text string for '{key}'; imputed using peer cohort median ({default_val:.2f}).")
                return default_val, False
            
            # Common survey text responses mapped to ordinal values
            text_map = {
                "never": 1.0, "rarely": 2.0, "sometimes": 3.0, "often": 4.0, "always": 5.0, "very often": 5.0,
                "strongly disagree": 1.0, "disagree": 2.0, "neutral": 3.0, "agree": 4.0, "strongly agree": 5.0,
                "daily": 4.0, "no effort": 1.0, "little effort": 2.0, "moderate effort": 3.0, "high effort": 4.0, "very high effort": 5.0
            }
            if val_clean in text_map:
                num = text_map[val_clean]
            else:
                try:
                    num = float(val)
                except (ValueError, TypeError):
                    warnings_list.append(f"Invalid text '{val}' for '{key}'; fell back safely to peer cohort median ({default_val:.2f}).")
                    return default_val, False
        else:
            try:
                num = float(val)
            except (ValueError, TypeError):
                warnings_list.append(f"Unparseable non-numeric value for '{key}'; fell back to peer cohort median ({default_val:.2f}).")
                return default_val, False

        # Check for NaN
        if np.isnan(num):
            warnings_list.append(f"Encountered NaN for '{key}'; imputed using peer cohort median ({default_val:.2f}).")
            return default_val, False

        # Determine boundaries
        min_bound, max_bound = 1.0, 5.0
        if key in ["age_group", "ai_usage_freq"]:
            min_bound, max_bound = 1.0, 4.0
        elif key in ["academic_year"]:
            min_bound, max_bound = 1.0, 6.0
        elif key.startswith("faculty_") or key.startswith("tool_") or key.startswith("purpose_") or key.startswith("delegate_"):
            min_bound, max_bound = 0.0, 1.0
        elif key in ["count_tools_used", "count_tasks_delegated", "count_purposes"]:
            min_bound, max_bound = 0.0, 10.0

        if np.isinf(num):
            if num > 0:
                warnings_list.append(f"Encountered +Infinity for '{key}'; clamped to upper domain boundary ({max_bound:.1f}).")
                return max_bound, True
            else:
                warnings_list.append(f"Encountered -Infinity for '{key}'; clamped to lower domain boundary ({min_bound:.1f}).")
                return min_bound, True

        # Check out-of-range
        if num < min_bound or num > max_bound:
            clamped = float(np.clip(num, min_bound, max_bound))
            warnings_list.append(f"Out-of-range numerical value ({num}) for '{key}' clamped to valid domain [{min_bound:.1f}, {max_bound:.1f}].")
            return clamped, True

        return float(num), True

    def transform_inputs(self, raw_dict: Dict[str, Any], warnings_list: List[str]) -> Tuple[pd.DataFrame, int]:
        """Construct full 68-feature vector from raw or partial user inputs.
        
        Returns:
            Tuple of (DataFrame with 68 features, count of valid user inputs)
        """
        cleaned = {}
        valid_user_features = 0

        # Scrub potential PII from input dictionary
        forbidden_keys = ["name", "email", "student_id", "it234", "timestamp", "participant_id", "phone", "phone_number"]
        for k in list(raw_dict.keys()):
            if any(term in k.lower() for term in forbidden_keys):
                warnings_list.append(f"Excluded forbidden identifier key: '{k}'")

        # Track recognized user inputs
        for feat in self.feature_names:
            if feat in raw_dict and raw_dict[feat] is not None:
                val, is_valid = self._clean_and_clamp(feat, raw_dict[feat], warnings_list)
                cleaned[feat] = val
                if is_valid:
                    valid_user_features += 1
            else:
                cleaned[feat] = float(self.default_features.get(feat, 0.0))

        def _get_or_clean(c: str) -> float:
            nonlocal valid_user_features
            if c in cleaned and (c in raw_dict):
                return float(cleaned[c])
            if c in raw_dict and raw_dict[c] is not None:
                v, is_v = self._clean_and_clamp(c, raw_dict[c], warnings_list)
                if is_v:
                    valid_user_features += 1
                return v
            return float(self.default_features.get(c, 3.0))

        # Check if high-level survey keys were passed to compute composites dynamically
        # 1. Verification composite
        verif_cols = ["Q2_verify_info", "Q3_compare_sources", "Q4_check_accuracy", "Q5_understand_reasoning", "Q6_modify_content"]
        if any(c in raw_dict for c in verif_cols):
            cleaned["composite_verification"] = float(np.mean([_get_or_clean(c) for c in verif_cols]))

        # 2. Autonomy composite
        auton_cols = ["Q7_attempt_independently", "Q8_complete_without_ai", "Q9_learning_assistant"]
        if any(c in raw_dict for c in auton_cols):
            cleaned["composite_autonomy"] = float(np.mean([_get_or_clean(c) for c in auton_cols]))

        # 3. Trust composite
        trust_cols = ["Q28_trust_reliable_info", "Q29_trust_consistent", "Q30_trust_accuracy",
                      "Q31_trust_explanations", "Q32_trust_clear_explanations", "Q33_trust_appropriate_support"]
        if any(c in raw_dict for c in trust_cols):
            cleaned["composite_trust"] = float(np.mean([_get_or_clean(c) for c in trust_cols]))

        # 4. TAM composite
        tam_cols = ["Q23_pu_improves_understanding", "Q24_pu_complete_effectively", "Q25_pu_productivity",
                    "Q26_pu_useful_for_goals", "Q27_pu_learn_difficult_topics"]
        if any(c in raw_dict for c in tam_cols):
            cleaned["composite_tam"] = float(np.mean([_get_or_clean(c) for c in tam_cols]))

        # 5. Self-efficacy composite
        se_cols = ["Q39_feel_capable", "Q40_feel_confident", "Q41_more_capable_after", "Q42_more_confident_after", "Q43_approach_challenging"]
        if any(c in raw_dict for c in se_cols):
            cleaned["composite_self_efficacy"] = float(np.mean([_get_or_clean(c) for c in se_cols]))

        # 6. Interaction terms
        cleaned["idx_automation_bias"] = cleaned["composite_trust"] - cleaned["composite_verification"]
        cleaned["idx_delegation_intensity"] = cleaned["ai_usage_freq"] * cleaned["Q20_task_delegation_freq"]
        cleaned["idx_passive_adoption"] = cleaned["Q1_direct_use_freq"] * (6.0 - cleaned["Q22_effort_on_ai_answers"])

        # 7. Meta-faculty resolution
        if "degree_field" in raw_dict and raw_dict["degree_field"]:
            faculty_cat = classify_meta_faculty(raw_dict["degree_field"])
            for f_col in ["faculty_Business_Economics", "faculty_Computing_IT", "faculty_Engineering",
                          "faculty_Humanities_Health_Other", "faculty_Natural_Applied_Sciences"]:
                cleaned[f_col] = 1.0 if f_col == f"faculty_{faculty_cat}" else 0.0
            valid_user_features += 1

        # 8. Multi-select tools handling
        if "tools_used" in raw_dict and raw_dict["tools_used"]:
            tools_list = [str(t).lower() for t in raw_dict["tools_used"]]
            cleaned["tool_chatgpt"] = 1.0 if any("chatgpt" in t for t in tools_list) else 0.0
            cleaned["tool_google_gemini"] = 1.0 if any("gemini" in t for t in tools_list) else 0.0
            cleaned["tool_microsoft_copilot"] = 1.0 if any("copilot" in t for t in tools_list) else 0.0
            cleaned["tool_claude"] = 1.0 if any("claude" in t for t in tools_list) else 0.0
            cleaned["tool_perplexity"] = 1.0 if any("perplexity" in t for t in tools_list) else 0.0
            cleaned["count_tools_used"] = float(len(tools_list))
            valid_user_features += 1

        # 9. Multi-select delegated tasks handling
        if "tasks_delegated" in raw_dict and raw_dict["tasks_delegated"]:
            tasks_list = [str(t).lower() for t in raw_dict["tasks_delegated"]]
            cleaned["delegate_writing_assignments"] = 1.0 if any("writing" in t for t in tasks_list) else 0.0
            cleaned["delegate_explaining_concepts"] = 1.0 if any("explaining" in t for t in tasks_list) else 0.0
            cleaned["delegate_summarising_materials"] = 1.0 if any("summaris" in t for t in tasks_list) else 0.0
            cleaned["delegate_creating_presentations"] = 1.0 if any("presentation" in t for t in tasks_list) else 0.0
            cleaned["delegate_programming_problems"] = 1.0 if any("programming" in t or "code" in t for t in tasks_list) else 0.0
            cleaned["delegate_mathematical_problems"] = 1.0 if any("math" in t or "calculat" in t for t in tasks_list) else 0.0
            cleaned["count_tasks_delegated"] = float(len(tasks_list))
            valid_user_features += 1

        # Check for unrecognized keys
        extra_helper_keys = {"tools_used", "ai_tools_used", "tasks_delegated", "tasks_delegated_types", "purposes_used", "ai_purposes"}
        known_keys = set(self.feature_names).union(verif_cols).union(auton_cols).union(trust_cols).union(tam_cols).union(se_cols).union(["degree_field"]).union(extra_helper_keys)
        for k in raw_dict:
            if k not in known_keys and not any(term in k.lower() for term in forbidden_keys):
                warnings_list.append(f"Ignored unrecognized input key: '{k}'")

        # Document missing optional feature count if at least one valid feature was provided
        if valid_user_features > 0:
            provided_count = sum(1 for feat in self.feature_names if feat in raw_dict and raw_dict[feat] is not None and not pd.isna(raw_dict[feat]))
            missing_count = len(self.feature_names) - provided_count
            if missing_count > 0:
                warnings_list.append(f"Handled {missing_count} missing optional features using peer cohort training medians.")

        return pd.DataFrame([cleaned])[self.feature_names], valid_user_features

    def predict(self, raw_input: Dict[str, Any], top_factors_count: int = 5) -> Dict[str, Any]:
        """Perform defensive inference and compute exact LinearSHAP explanations."""
        warnings_list = []

        if raw_input is None or not isinstance(raw_input, dict) or len(raw_input) == 0:
            return {
                "status": "validation_error",
                "error_type": "MissingRequiredInput",
                "message": "Validation Error: Empty input provided. A cognitive offloading assessment requires at least one answered student habit or academic question. Empty submissions cannot be evaluated.",
                "predicted_category": None,
                "continuous_risk_score": None,
                "raw_regression_score": None,
                "score_scale": "1.0 - 5.0 (Likert unweighted construct mean)",
                "confidence": None,
                "probabilities": None,
                "probability_interpretation": PROBABILITY_EXPLANATION,
                "top_contributing_factors": [],
                "disclaimer": DISCLAIMER,
                "warnings": ["Submission was empty."],
                "warnings_count": 1
            }

        df_features, valid_user_features = self.transform_inputs(raw_input, warnings_list)

        if valid_user_features == 0:
            return {
                "status": "validation_error",
                "error_type": "MissingRequiredInput",
                "message": "Validation Error: No valid student habit survey responses were found in the submission. All provided fields were unrecognized, empty, or unparseable. At least one valid question rating is required.",
                "predicted_category": None,
                "continuous_risk_score": None,
                "raw_regression_score": None,
                "score_scale": "1.0 - 5.0 (Likert unweighted construct mean)",
                "confidence": None,
                "probabilities": None,
                "probability_interpretation": PROBABILITY_EXPLANATION,
                "top_contributing_factors": [],
                "disclaimer": DISCLAIMER,
                "warnings": warnings_list,
                "warnings_count": len(warnings_list)
            }

        # 1. Continuous Latent Score & Range-Constrained Score
        if hasattr(self.model, "predict"):
            pred_score = float(self.model.predict(df_features)[0])
        elif hasattr(self.model, "reg_"):
            pred_score = float(self.model.reg_.predict(df_features)[0])
        elif self.continuous_reg is not None:
            pred_score = float(self.continuous_reg.predict(df_features)[0])
        else:
            pred_score = 3.0

        raw_regression_score = float(pred_score)
        continuous_risk_score = float(np.clip(pred_score, 1.0, 5.0))

        # Check if clamping occurred and log transparent notice
        if raw_regression_score > 5.0:
            warnings_list.append(
                f"Continuous latent regression score ({raw_regression_score:.3f}) exceeded theoretical construct upper bound and was clamped to 5.000."
            )
        elif raw_regression_score < 1.0:
            warnings_list.append(
                f"Continuous latent regression score ({raw_regression_score:.3f}) fell below theoretical construct lower bound and was clamped to 1.000."
            )

        # Class prediction via calibrated thresholds
        if pred_score <= self.cut1:
            predicted_class = "Low"
        elif pred_score <= self.cut2:
            predicted_class = "Medium"
        else:
            predicted_class = "High"

        # 2. Probability Estimation via Predictive Density (residual std)
        std = self.residual_std
        p0 = norm.cdf(self.cut1, loc=pred_score, scale=std)
        p1 = norm.cdf(self.cut2, loc=pred_score, scale=std) - p0
        p2 = 1.0 - norm.cdf(self.cut2, loc=pred_score, scale=std)
        probs_raw = np.array([p0, p1, p2], dtype=float)
        probs_raw = np.clip(probs_raw, 0.0, 1.0)
        probs_sum = np.sum(probs_raw)
        if probs_sum > 0:
            probs = probs_raw / probs_sum
        else:
            probs = np.array([1/3, 1/3, 1/3])

        p_low = round(float(probs[0]), 4)
        p_med = round(float(probs[1]), 4)
        p_high = round(1.0 - p_low - p_med, 4)
        p_high = max(0.0, min(1.0, p_high))

        calibrated_probs = {
            "low": p_low,
            "medium": p_med,
            "high": p_high
        }
        confidence = float(calibrated_probs[predicted_class.lower()])

        # 3. Exact LinearSHAP Feature Contributions: phi_j = beta_j * (x_j - x_bar_j)
        contributing_factors = []
        if self.coefficients is not None:
            x_vals = df_features.iloc[0].values
            x_means = np.array([self.background_means[col] for col in self.feature_names])
            linear_shap_vals = self.coefficients * (x_vals - x_means)

            top_indices = np.argsort(np.abs(linear_shap_vals))[::-1][:top_factors_count]
            for idx in top_indices:
                feat_name = self.feature_names[idx]
                val = float(x_vals[idx])
                contrib = float(linear_shap_vals[idx])
                effect = "increases predicted risk" if contrib > 0 else "mitigates predicted risk"
                human_label = FEATURE_HUMAN_LABELS.get(feat_name, feat_name.replace("_", " ").title())
                explanation_dict = FEATURE_PLAIN_EXPLANATIONS.get(feat_name, {})
                if effect in explanation_dict:
                    plain_explanation = explanation_dict[effect]
                elif effect == "increases predicted risk":
                    plain_explanation = f"Higher reliance on {human_label.lower()} contributes toward elevated offloading risk."
                else:
                    plain_explanation = f"Active habits regarding {human_label.lower()} help protect independent learning."

                contributing_factors.append({
                    "feature_name": feat_name,
                    "human_label": human_label,
                    "student_value": round(val, 2),
                    "linear_shap_contribution": round(contrib, 4),
                    "effect": effect,
                    "plain_explanation": plain_explanation
                })

        return {
            "status": "success",
            "model_architecture": "Thresholded Ridge Regressor (Ordinal)",
            "predicted_category": predicted_class,
            "continuous_risk_score": round(continuous_risk_score, 3),
            "raw_regression_score": round(raw_regression_score, 3),
            "score_scale": "1.0 - 5.0 (Likert unweighted construct mean)",
            "confidence": round(confidence, 4),
            "probabilities": calibrated_probs,
            "probability_interpretation": PROBABILITY_EXPLANATION,
            "top_contributing_factors": contributing_factors,
            "disclaimer": DISCLAIMER,
            "warnings": warnings_list,
            "warnings_count": len(warnings_list)
        }


